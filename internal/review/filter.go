package review

import (
	"regexp"
	"strings"

	"github.com/divmora/code-review-bot/internal/config"
	"github.com/divmora/code-review-bot/pkg/diff"
)

// defaultIgnores are never worth an LLM review.
var defaultIgnores = []string{
	// lockfiles
	"package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "go.sum", "Cargo.lock",
	"poetry.lock", "Pipfile.lock", "uv.lock", "composer.lock", "Gemfile.lock", "*.lock",
	// build output and vendored code
	"vendor/", "node_modules/", "dist/", "build/", "out/", ".next/", "target/", "__pycache__/",
	// generated and minified
	"*.min.js", "*.min.css", "*.map", "*.pb.go", "*_pb2.py", "*.gen.go", "*_generated.go", "*.snap",
	// assets
	"*.svg", "*.png", "*.jpg", "*.jpeg", "*.gif", "*.webp", "*.ico", "*.pdf", "*.woff", "*.woff2", "*.ttf", "*.eot",
	"*.zip", "*.gz", "*.tar", "*.jar", "*.exe", "*.dll", "*.so", "*.dylib",
}

var generatedHeader = regexp.MustCompile(`(?i)(code generated .* do not edit|@generated|auto-generated file|autogenerated by)`)

// Skip reasons that leave nothing unreviewed the repository didn't accept:
// path_filters come from the base branch, and a file with no textual
// change (a pure rename, a mode change) has no code to review.
const (
	SkipPathFilters   = "excluded by path_filters"
	SkipNoTextChanges = "no textual changes"
)

// Unreviewed reports whether a skipped file holds a change nobody reviewed
// that the repository's own config didn't exclude: deleted, binary,
// truncated, generated, ignored by default or deletion-only. The PR's
// author controls those files, so they keep the bot from approving.
func (s SkippedFile) Unreviewed() bool {
	return s.Reason != SkipPathFilters && s.Reason != SkipNoTextChanges
}

// skipReason says why a file is not reviewed, or "" to review it.
func skipReason(f *diff.File, rc *config.RepoConfig) string {
	switch {
	case f.Status == diff.Deleted:
		return "deleted"
	case f.Binary:
		return "binary"
	case f.Truncated:
		return "diff too large for the code host API"
	case len(f.Hunks) == 0:
		return SkipNoTextChanges
	}
	if !rc.IncludePath(f.Path) {
		return SkipPathFilters
	}
	// Repo include patterns may re-include defaults, e.g. "dist/keep.js".
	for _, p := range defaultIgnores {
		if config.Match(p, f.Path) && !explicitlyIncluded(rc, f.Path) {
			return "ignored by default (lockfile, generated, vendored or asset)"
		}
	}
	if f.AddedCount() == 0 {
		return "only deletions"
	}
	for _, h := range f.Hunks {
		for i, l := range h.Lines {
			if i > 5 {
				break
			}
			if h.NewStart <= 3 && generatedHeader.MatchString(l.Text) {
				return "generated file"
			}
		}
	}
	return ""
}

func explicitlyIncluded(rc *config.RepoConfig, p string) bool {
	for _, f := range rc.PathFilters {
		if !strings.HasPrefix(f, "!") && config.Match(f, p) && strings.ContainsAny(f, "/") {
			return true
		}
	}
	return false
}
